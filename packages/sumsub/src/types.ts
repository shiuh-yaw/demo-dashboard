export type SumsubWebhookType =
  | "applicantReviewed"
  | "applicantPending"
  | "applicantCreated"
  | "applicantOnHold"
  | "applicantActionPending"
  | "applicantActionReviewed"
  | "applicantActionOnHold"
  | "applicantReset"
  | "applicantPersonalInfoChanged"
  | "applicantPrechecked"
  | "videoIdentStatusChanged"
  | "applicantDeleted"
  | "applicantLevelChanged"
  | "applicantWorkflowCompleted"
  | string;

export interface SumsubWebhookPayload {
  applicantId: string;
  inspectionId?: string;
  correlationId?: string;
  externalUserId?: string;
  type: SumsubWebhookType;
  reviewResult?: ApplicantReviewResult;
  reviewStatus?: ApplicantReviewStatus;
  createdAtMs?: string;
  sandboxMode?: boolean;
  [key: string]: unknown;
}

// ---------------------------------------------------------------------------
// Client interface
// ---------------------------------------------------------------------------

export interface ISumsubClient {
  /** Create a new applicant. */
  createApplicant(request: CreateApplicantRequest): Promise<Applicant>;

  /** Get an applicant by SumSub id. */
  getApplicant(applicantId: string): Promise<Applicant>;

  /** Get an applicant by external user id. */
  getApplicantByExternalId(externalUserId: string): Promise<Applicant>;

  /** Get the verification status of an applicant. */
  getApplicantStatus(applicantId: string): Promise<ApplicantReview>;

  /** Generate an SDK access token for client-side verification. */
  generateAccessToken(request: GenerateAccessTokenRequest): Promise<AccessToken>;

  /** Generate a share token for reliance KYC / token sharing. */
  generateShareToken(request: GenerateShareTokenRequest): Promise<AccessToken>;

  /**
   * Consume a share token to create an applicant from shared identity data.
   * This is the receiving side of SumSub reliance KYC.
   */
  reuseIdentity(request: ReuseIdentityRequest): Promise<Applicant>;

  /** Preview what data a share token contains before consuming it. */
  previewReuseIdentity(request: ReuseIdentityRequest): Promise<ReuseIdentityPreview>;

  /** Reset an applicant's verification (sandbox). */
  resetApplicant(applicantId: string): Promise<void>;
}
