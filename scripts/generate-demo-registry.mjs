#!/usr/bin/env node
// Generate .claude/demo-registry.md + .claude/demo-registry.json from
// every packages/*/AGENTS.md and apps/*/AGENTS.md frontmatter.
//
// Phase 3 of the demo meta-system. See docs/projects/demo-meta-system/
// phases/03-agents-md.md.
//
// Usage: pnpm registry        (calls `node scripts/generate-demo-registry.mjs`)
// Or in CI:  node scripts/generate-demo-registry.mjs --check
//
// --check exits non-zero if the on-disk registry differs from the
// regenerated registry (forces authors to commit registry updates with
// the AGENTS.md change in the same PR).
import { writeFileSync, readFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { findAgentsMdFiles, readAgentsMd } from "./agents-md-shared.mjs";

const __filename = fileURLToPath(import.meta.url);
const REPO_ROOT = join(dirname(__filename), "..");

const checkMode = process.argv.includes("--check");

const targets = findAgentsMdFiles(REPO_ROOT)
  .map((t) => {
    const { frontmatter, lineCount } = readAgentsMd(t.path);
    return { ...t, frontmatter, lineCount };
  })
  .filter((t) => t.frontmatter)
  .sort((a, b) => `${a.kind}:${a.dir}`.localeCompare(`${b.kind}:${b.dir}`));

const apps = targets.filter((t) => t.kind === "app");
const packages = targets.filter((t) => t.kind === "package");

const groupBy = (arr, keyFn) => {
  const map = new Map();
  for (const item of arr) {
    const k = keyFn(item) ?? "_unknown";
    if (!map.has(k)) map.set(k, []);
    map.get(k).push(item);
  }
  return map;
};

const flowRoleGroups = groupBy(packages, (p) => p.frontmatter.flow_role);

const sectionConfig = [
  ["onramp", "Onramp providers"],
  ["offramp", "Offramp providers"],
  ["bridge", "Bridge / swap providers"],
  ["wallet", "Wallet providers"],
  ["auth", "Auth providers"],
  ["checkout", "Checkout providers"],
  ["payouts", "Payouts providers"],
  ["theming", "Theming primitives"],
  ["shared-ui", "Shared UI"],
  ["utility", "Utilities"],
];

const md = [];
md.push("# Demo registry");
md.push("");
md.push(
  "> Auto-generated by `scripts/generate-demo-registry.mjs` from every `packages/*/AGENTS.md` and `apps/*/AGENTS.md` frontmatter. Do not hand-edit. Re-run with `pnpm registry` after updating any AGENTS.md."
);
md.push("");
md.push("## Demo apps");
md.push("");
md.push("| App | flow_role | custody | status |");
md.push("|---|---|---|---|");
for (const a of apps) {
  md.push(
    `| \`${a.dir}\` | ${a.frontmatter.flow_role ?? "?"} | ${a.frontmatter.custody ?? "?"} | ${a.frontmatter.status ?? "?"} |`
  );
}
md.push("");

for (const [role, title] of sectionConfig) {
  const items = flowRoleGroups.get(role) ?? [];
  if (items.length === 0) continue;
  md.push(`## ${title}`);
  md.push("");
  const isRamp = role === "onramp" || role === "offramp";
  if (isRamp) {
    md.push("| Package | Provider | custody | regions | status |");
    md.push("|---|---|---|---|---|");
    for (const p of items) {
      const f = p.frontmatter;
      const regions = Array.isArray(f.regions)
        ? f.regions
            .map((r) => `${r.country}/${r.currency}${Array.isArray(r.rails) ? ` (${r.rails.join(", ")})` : ""}`)
            .join("; ")
        : "—";
      md.push(
        `| \`${p.dir}\` | ${f.provider?.name ?? "—"} | ${f.custody ?? "?"} | ${regions} | ${f.status ?? "?"} |`
      );
    }
  } else {
    md.push("| Package | Provider | custody | status |");
    md.push("|---|---|---|---|");
    for (const p of items) {
      const f = p.frontmatter;
      md.push(
        `| \`${p.dir}\` | ${f.provider?.name ?? "—"} | ${f.custody ?? "?"} | ${f.status ?? "?"} |`
      );
    }
  }
  md.push("");
}

const ungrouped = packages.filter(
  (p) => !sectionConfig.some(([role]) => role === p.frontmatter.flow_role)
);
if (ungrouped.length) {
  md.push("## Other packages");
  md.push("");
  md.push("| Package | flow_role | status |");
  md.push("|---|---|---|");
  for (const p of ungrouped) {
    md.push(`| \`${p.dir}\` | ${p.frontmatter.flow_role ?? "?"} | ${p.frontmatter.status ?? "?"} |`);
  }
  md.push("");
}

const mdOut = md.join("\n").replace(/\n+$/, "") + "\n";

const json = {
  generatedAt: null, // intentionally omitted so the file is byte-stable in CI
  apps: apps.map((a) => ({ name: a.dir, ...a.frontmatter })),
  packages: packages.map((p) => ({ name: p.dir, ...p.frontmatter })),
};
const jsonOut = JSON.stringify(json, null, 2) + "\n";

const claudeDir = join(REPO_ROOT, ".claude");
if (!existsSync(claudeDir)) mkdirSync(claudeDir, { recursive: true });
const mdPath = join(claudeDir, "demo-registry.md");
const jsonPath = join(claudeDir, "demo-registry.json");

if (checkMode) {
  let mdOnDisk = "";
  let jsonOnDisk = "";
  try {
    mdOnDisk = readFileSync(mdPath, "utf8");
  } catch {}
  try {
    jsonOnDisk = readFileSync(jsonPath, "utf8");
  } catch {}
  if (mdOnDisk !== mdOut || jsonOnDisk !== jsonOut) {
    console.error("::error::Demo registry is stale. Run `pnpm registry` and commit the result.");
    if (mdOnDisk !== mdOut) {
      console.error(`  ${relative(REPO_ROOT, mdPath)} differs.`);
    }
    if (jsonOnDisk !== jsonOut) {
      console.error(`  ${relative(REPO_ROOT, jsonPath)} differs.`);
    }
    process.exit(1);
  }
  console.log("Demo registry is up to date.");
  process.exit(0);
}

writeFileSync(mdPath, mdOut);
writeFileSync(jsonPath, jsonOut);
console.log(`Wrote ${relative(REPO_ROOT, mdPath)} and ${relative(REPO_ROOT, jsonPath)}.`);
console.log(`  apps: ${apps.length}, packages: ${packages.length}`);
